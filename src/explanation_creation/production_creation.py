"""
Generates explanations for a production set through the LiteLLM proxy (the same client setup the judge
uses), in parallel and resumable. One script for all three datasets; the dataset decides the prompt:

  - bgl, thunderbird: src/prompts/bgl/prompt2.py -- every log line carries its ground-truth
    [normal]/[abnormal] tag (shown exactly as the judge sees the lines).
  - hdfs: src/prompts/hdfs/prompt1.py -- HDFS is session-based, so there are no per-line tags and the
    block-level classification is all the model gets (same as the gold set).

The gold set was generated by src/explanation_creation/<dataset>/creation1.py (OpenAI, blind); those scripts
stay as they are so the gold set remains reproducible.

Stamps `metadata.llm` and resets `metadata.hallucination-check` to unverified, like creation1.py. Records
that already have an explanation pass through unchanged. An answer must start with "This log sequence is
<classification> because"; otherwise it is asked again (up to --max_attempts), and if it still does not, the
record is left without an explanation and retried on the next run.

Resumable: each finished explanation is appended to `<output_path>.explanations.jsonl` right away; re-running
the same command reuses them (a changed prompt, model or setting is generated again).

Needs LITELLM_API_KEY and LITELLM_API_BASE (a local .env works). Run from the repo root:

    uv run python -m src.explanation_creation.production_creation --dataset bgl --llm_model <model>
"""

import argparse
import hashlib
import itertools
import json
import os
from datetime import datetime, timezone

from dotenv import load_dotenv
from json_stream import load, streamable_list

from src.help_functions.cached_parallel import process_records
from src.help_functions.human_review_io import format_logs_for_review
from src.help_functions.json_deep_convert import deep_convert
from src.help_functions.manifest_log import append_manifest_entry
from src.prompts.bgl import prompt2 as labeled_prompt
from src.prompts.hdfs import prompt1 as hdfs_prompt
from src.review.validate_judge.gold import DATASETS
from src.review.validate_judge.judge import MAX_OUTPUT_TOKENS, REQUEST_TIMEOUT_S, _content_text

load_dotenv()

PER_LINE_LABELS = {"bgl": True, "thunderbird": True, "hdfs": False}
PROMPT_TEMPLATE_ID = {"bgl": "bgl/prompt2", "thunderbird": "bgl/prompt2", "hdfs": "hdfs/prompt1"}

_llm_cache: dict = {}


def _chat_llm(model: str, temperature: float, effort: str = None):
    """Plain chat model on the LiteLLM proxy; same construction as validate_judge/judge.py::_structured_llm
    minus the structured output. `reasoning_effort` is only sent when --effort is given."""
    key = (model, temperature, effort)
    if key not in _llm_cache:
        import litellm
        from langchain_litellm import ChatLiteLLM

        litellm.drop_params = False  # see judge.py: drop_params would silently strip reasoning_effort
        model_kwargs = {"reasoning_effort": effort, "allowed_openai_params": ["reasoning_effort"]} if effort else {}
        _llm_cache[key] = ChatLiteLLM(
            model=model,
            temperature=temperature,
            api_key=os.environ.get("LITELLM_API_KEY"),
            api_base=os.environ.get("LITELLM_API_BASE"),
            custom_llm_provider="openai",
            request_timeout=REQUEST_TIMEOUT_S,
            max_tokens=MAX_OUTPUT_TOKENS,
            model_kwargs=model_kwargs,
            max_retries=0,
        )
    return _llm_cache[key]


def build_prompt(dataset: str, record: dict) -> str:
    classification = "abnormal" if record["classification"] == "anomaly" else record["classification"]
    if PER_LINE_LABELS[dataset]:
        raw_logs = record["metadata"]["raw_content"].get("raw_log_sequence")
        if not raw_logs:
            raise ValueError("record has no raw_log_sequence, which the per-line tags are derived from")
        return labeled_prompt.get_prompt(
            log_lines=format_logs_for_review(record["input"], raw_logs, session_based=False),
            sequence_classification=classification,
            dataset_name=dataset,
        )
    return hdfs_prompt.get_prompt(
        log_sequence=list(record["input"]), sequence_classification=classification, dataset_name=dataset)


def _opening(record: dict) -> str:
    classification = "abnormal" if record["classification"] == "anomaly" else record["classification"]
    return f"This log sequence is {classification} because"


def generate_records(records, dataset: str, llm_model: str, temperature: float, effort: str, cache_path: str,
                     stats: dict, max_workers: int = 8, max_attempts: int = 3, invoke_fn=None):
    """Yields every record in order, with `explanation` and `metadata.llm` filled in where one was generated.
    `invoke_fn(prompt) -> str` replaces the LLM call (tests)."""
    params = {"temperature": temperature, "reasoning_effort": effort, "per_log_labels": PER_LINE_LABELS[dataset]}
    template_id = PROMPT_TEMPLATE_ID[dataset]

    def invoke(prompt: str) -> str:
        if invoke_fn:
            return invoke_fn(prompt)
        return _content_text(_chat_llm(llm_model, temperature, effort).invoke(prompt).content).strip()

    def key_fn(record):
        setting = json.dumps([llm_model, template_id, params], sort_keys=True)
        digest = hashlib.sha256((build_prompt(dataset, record) + setting).encode()).hexdigest()[:16]
        return f"{record['metadata']['identity']['id']}|{digest}"

    def compute(record):
        prompt = build_prompt(dataset, record)
        opening = _opening(record)
        for _ in range(max_attempts):
            text = invoke(prompt)
            if text.startswith(opening):
                return {"explanation": text, "generation_timestamp": str(datetime.now())}
        raise ValueError(f"no answer starting with {opening!r} after {max_attempts} attempts; last: {text[:120]!r}")

    def apply(record, payload):
        record["explanation"] = payload["explanation"]
        record["metadata"]["llm"] = {
            "model": llm_model,
            "generation_timestamp": payload["generation_timestamp"],
            "prompt_template_id": template_id,
            "generation_params": params,
        }
        record["metadata"]["hallucination-check"] = {
            "verification_status": "unverified",
            "verification_method": None,
            "verifier_model": None,
            "hallucination_flags": None,
            "corrected_reasoning_text": None,
            "human_reviewed": False,
            "reviewer_id": None,
            "review_notes": None,
        }
        return record

    def on_failure(record, error):
        print(f"  generation failed for {record['metadata']['identity']['id']}: {type(error).__name__}: {error}")
        return record  # explanation stays empty, so the next run tries it again

    return process_records(
        records, key_fn=key_fn, compute=compute, apply=apply, on_failure=on_failure,
        cache_path=cache_path, stats=stats, max_workers=max_workers,
        skip=lambda record: bool(record.get("explanation")),
    )


@streamable_list
def _stream(input_path, limit, **kwargs):
    with open(input_path, "r", encoding="utf-8") as f:
        records = (deep_convert(item) for item in load(f).persistent())
        if limit > 0:
            records = itertools.islice(records, limit)
        yield from generate_records(records, **kwargs)


def main(dataset: str, input_path: str, output_path: str, llm_model: str, temperature: float, effort: str,
         manifest_path: str, max_workers: int = 8, max_attempts: int = 3, limit: int = -1):
    for var in ("LITELLM_API_KEY", "LITELLM_API_BASE"):
        if not os.environ.get(var):
            raise SystemExit(f"{var} is not set (put it in .env or export it).")

    cache_path = f"{output_path}.explanations.jsonl"
    stats = {"total": 0, "skipped": 0, "from_cache": 0, "computed": 0, "failed": 0}

    tmp_path = f"{output_path}.tmp"
    with open(tmp_path, "w", encoding="utf-8") as f:
        json.dump(_stream(input_path, limit, dataset=dataset, llm_model=llm_model, temperature=temperature,
                          effort=effort, cache_path=cache_path, stats=stats, max_workers=max_workers,
                          max_attempts=max_attempts), f, indent=4)
    os.replace(tmp_path, output_path)  # a crash mid-run leaves any earlier output intact; the cache lets it resume

    print(f"Done: {stats}. Wrote {output_path}")

    append_manifest_entry(manifest_path, {
        "step": 6,
        "action": "explanation_generation_run",
        "timestamp": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "dataset": dataset,
        "stratum": "production",
        "params": {
            "model": llm_model,
            "temperature": temperature,
            "reasoning_effort": effort,
            "prompt_template_id": PROMPT_TEMPLATE_ID[dataset],
            "per_log_labels": PER_LINE_LABELS[dataset],
        },
        "inputs": [input_path],
        "outputs": [output_path, cache_path],
        "metrics": {},
        "notes": (
            f"{stats['computed']} explanations generated, {stats['from_cache']} reused from the cache file, "
            f"{stats['skipped']} skipped (already had an explanation), {stats['failed']} failed (left empty, "
            f"retried on re-run) out of {stats['total']} records read."
        ),
    })


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Generate production-set explanations through the LiteLLM proxy.")
    parser.add_argument("--dataset", required=True, choices=DATASETS)
    parser.add_argument("--llm_model", required=True, help="Model name on the LiteLLM proxy.")
    parser.add_argument("--input_path", default=None,
                        help="Default: dataset_short/<dataset>/production_not_explained.json")
    parser.add_argument("--output_path", default=None,
                        help="Default: dataset_short/<dataset>/production_explained.json")
    parser.add_argument("--temperature", type=float, default=0.25)
    parser.add_argument("--effort", default=None, help="Reasoning effort sent to the model; omitted when not given.")
    parser.add_argument("--max_workers", type=int, default=8, help="Parallel LLM calls.")
    parser.add_argument("--max_attempts", type=int, default=3,
                        help="Tries per record when the answer does not start with the required opening phrase.")
    parser.add_argument("--limit", type=int, default=-1,
                        help="Only handle the first N records of the input (smoke test). -1 for all. The output "
                             "then holds only those N records, so give it a different --output_path.")
    parser.add_argument("--manifest_path", default="docs/llm_judge_validation_log.json")
    args = parser.parse_args()

    main(
        dataset=args.dataset,
        input_path=args.input_path or f"dataset_short/{args.dataset}/production_not_explained.json",
        output_path=args.output_path or f"dataset_short/{args.dataset}/production_explained.json",
        llm_model=args.llm_model,
        temperature=args.temperature,
        effort=args.effort,
        manifest_path=args.manifest_path,
        max_workers=args.max_workers,
        max_attempts=args.max_attempts,
        limit=args.limit,
    )
